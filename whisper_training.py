import numpy as np

def extract_audio_features(example):
    audio_decoder = example['audio']

    # Get AudioSamples object
    samples = audio_decoder.get_all_samples()

    # Extract waveform (torch.Tensor) and sampling rate
    wave = samples.data
    sr = samples.sample_rate

    # Convert to 1D numpy array (mono)
    # .mean(0) averages across channels if stereo, otherwise it's already mono
    wave_mono = wave.mean(0).cpu().numpy()

    # Construct the new audio dictionary
    audio_dict = {
        'array': wave_mono,
        'sampling_rate': sr
    }

    return {
        'audio': audio_dict,
        'raw_transcription': example['raw_transcription']
    }

