def run_ffmpeg_cut(in_path, out_path, start_s, end_s, sr=16000):
    pathlib.Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    cmd = [
        "ffmpeg", "-y",
        "-ss", str(start_s),
        "-to", str(end_s),
        "-i", in_path,
        "-ac", "1",
        "-ar", str(sr),
        out_path
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

def is_useless_segment(seg):
    txt = (seg.get("text") or "").strip()
    if txt in {"", ".", "…"}:
        return True
    # if present, skip likely-silence segments (your file shows this field exists) :contentReference[oaicite:3]{index=3}
    nsp = seg.get("no_speech_prob", None)
    if nsp is not None and float(nsp) >= 0.6:
        return True
    return False

def merge_segments_into_chunks(segments):
    chunks = []
    cur = []
    cur_start = None
    cur_end = None

    def flush():
        nonlocal cur, cur_start, cur_end
        if not cur:
            return
        text = " ".join([s["text"].strip() for s in cur]).strip()
        if text:
            chunks.append({"start": cur_start, "end": cur_end, "text": text})
        cur, cur_start, cur_end = [], None, None

    for seg in segments:
        if is_useless_segment(seg):
            continue

        s = float(seg["start"])
        e = float(seg["end"])
        t = seg.get("text", "").strip()

        if cur_start is None:
            cur_start = s
        cur_end = e
        cur.append({"start": s, "end": e, "text": t})

        dur = cur_end - cur_start
        tok_len = len(processor.tokenizer.encode(" ".join([x["text"] for x in cur]).lower()))

        if dur >= MAX_CHUNK_SECONDS or tok_len >= MAX_LABEL_TOKENS:
            flush()

    flush()
    return chunks

